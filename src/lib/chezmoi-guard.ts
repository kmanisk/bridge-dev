import { spawn } from "node:child_process";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";

export type ChezmoiPathKind = "source" | "managed_target" | "generated_target" | "unmanaged" | "outside_destination" | "unavailable";

export interface ChezmoiOptions {
  sourceDir?: string;
  destinationDir?: string;
  executable?: string;
}

export interface ChezmoiInspection {
  requestedPath: string;
  canonicalPath: string;
  kind: ChezmoiPathKind;
  sourcePath?: string;
  sourceIsTemplate?: boolean;
  sourceDirty?: boolean;
  targetStatus?: string;
  generatedMarker?: string;
  explanation: string;
}

function inside(candidate: string, root: string): boolean {
  const relative = path.relative(root, candidate);
  return relative === "" || (relative !== ".." && !relative.startsWith(".." + path.sep) && !path.isAbsolute(relative));
}

async function canonicalPath(input: string): Promise<string> {
  const resolved = path.resolve(input);
  try {
    return await fs.realpath(resolved);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  let ancestor = path.dirname(resolved);
  const segments = [path.basename(resolved)];
  for (;;) {
    try {
      return path.join(await fs.realpath(ancestor), ...segments);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT" || ancestor === path.dirname(ancestor)) throw error;
      segments.unshift(path.basename(ancestor));
      ancestor = path.dirname(ancestor);
    }
  }
}

interface CommandResult { code: number; stdout: string; stderr: string }

function execute(executable: string, args: string[], timeoutMs = 6000): Promise<CommandResult> {
  return new Promise((resolve, reject) => {
    const child = spawn(executable, args, { stdio: ["ignore", "pipe", "pipe"] });
    let stdout = "";
    let stderr = "";
    let finished = false;
    const finish = (error?: Error, result?: CommandResult) => {
      if (finished) return;
      finished = true;
      clearTimeout(timer);
      if (error) reject(error);
      else resolve(result!);
    };
    const timer = setTimeout(() => {
      child.kill("SIGKILL");
      finish(new Error("Command timeout: " + executable));
    }, timeoutMs);
    child.stdout.on("data", (chunk: Buffer) => { stdout += chunk.toString().slice(0, 16384); stdout = stdout.slice(0, 16384); });
    child.stderr.on("data", (chunk: Buffer) => { stderr += chunk.toString().slice(0, 8192); stderr = stderr.slice(0, 8192); });
    child.on("error", (error) => finish(error));
    child.on("close", (code) => finish(undefined, { code: code ?? 1, stdout: stdout.trim(), stderr: stderr.trim() }));
  });
}

async function generatedComment(filePath: string): Promise<string | undefined> {
  try {
    const file = await fs.open(filePath, "r");
    try {
      const bytes = Buffer.alloc(1024);
      const { bytesRead } = await file.read(bytes, 0, bytes.length, 0);
      const header = bytes.subarray(0, bytesRead).toString("utf8").split("\n").slice(0, 5);
      const marker = header.find((line) => /^\s*(?:#|\/\/|;|\/\*)\s*.*\b(?:auto-?generated|generated by)\b.*\bdo not edit\b/i.test(line));
      return marker?.trim();
    } finally {
      await file.close();
    }
  } catch (error) {
    if (["ENOENT", "EISDIR"].includes((error as NodeJS.ErrnoException).code || "")) return undefined;
    throw error;
  }
}

export async function inspectChezmoiPath(input: string, options: ChezmoiOptions = {}): Promise<ChezmoiInspection> {
  const requestedPath = path.resolve(input);
  const sourceDir = await canonicalPath(options.sourceDir || process.env.LOCAL_CODER_CHEZMOI_SOURCE_DIR || path.join(os.homedir(), ".local/share/chezmoi"));
  const destinationDir = await canonicalPath(options.destinationDir || process.env.LOCAL_CODER_CHEZMOI_DESTINATION_DIR || os.homedir());
  const canonical = await canonicalPath(requestedPath);
  const base = { requestedPath, canonicalPath: canonical };

  if (inside(canonical, sourceDir) && !inside(requestedPath, sourceDir)) {
    return { ...base, kind: "managed_target", sourcePath: canonical, sourceIsTemplate: canonical.endsWith(".tmpl"), explanation: "Symlink alias to chezmoi source; edit its explicit canonical source path." };
  }
  if (inside(canonical, sourceDir)) {
    return { ...base, kind: "source", sourcePath: canonical, sourceIsTemplate: canonical.endsWith(".tmpl"), explanation: "Chezmoi source; edit explicitly and validate before applying." };
  }
  if (!inside(canonical, destinationDir)) {
    return { ...base, kind: "outside_destination", explanation: "Not inside the chezmoi destination; normal filesystem policy applies." };
  }

  const executable = options.executable || "chezmoi";
  const args = ["--source", sourceDir, "--destination", destinationDir, "source-path", canonical];
  let result: CommandResult;
  try {
    result = await execute(executable, args);
  } catch (error) {
    return { ...base, kind: "unavailable", explanation: "Cannot resolve chezmoi ownership: " + (error instanceof Error ? error.message : String(error)) };
  }

  if (result.code === 0) {
    const sourcePath = path.resolve(result.stdout.split("\n")[0] || "");
    if (!inside(sourcePath, sourceDir)) {
      return { ...base, kind: "unavailable", explanation: "Chezmoi returned an unexpected source outside its configured directory." };
    }
    const sourceIsTemplate = sourcePath.endsWith(".tmpl");
    let sourceDirty: boolean | undefined;
    let targetStatus: string | undefined;
    try {
      const git = await execute("git", ["-C", sourceDir, "status", "--porcelain", "--", path.relative(sourceDir, sourcePath)]);
      if (git.code === 0) sourceDirty = git.stdout.length > 0;
    } catch {}
    try {
      const status = await execute(executable, ["--source", sourceDir, "--destination", destinationDir, "--no-pager", "status", canonical]);
      if (status.code === 0) targetStatus = status.stdout || "in_sync";
    } catch {}
    return {
      ...base, kind: "managed_target", sourcePath, sourceIsTemplate, sourceDirty, targetStatus,
      explanation: "Managed target. Do not edit the live path; edit its chezmoi source and apply separately after validation.",
    };
  }

  if (!/not managed/i.test(result.stderr + " " + result.stdout)) {
    return { ...base, kind: "unavailable", explanation: "Chezmoi ownership lookup failed: " + (result.stderr || "exit " + result.code) };
  }
  const marker = await generatedComment(canonical);
  if (marker) {
    return { ...base, kind: "generated_target", generatedMarker: marker, explanation: "Generated output with a do-not-edit header. Use the owning generator/helper." };
  }
  return { ...base, kind: "unmanaged", explanation: "Unmanaged destination file. Do not auto-adopt it into chezmoi." };
}

/** Resolve a targeted edit to chezmoi source. Full replacements demand an exact source hash and a clean source. */
export async function resolveChezmoiEditTarget(
  requestedPath: string,
  mode: "targeted" | "replace" = "targeted",
  expectedSourceHash?: string,
  options: ChezmoiOptions = {}
): Promise<{ path: string; requestedPath: string; redirected: boolean; sourceIsTemplate: boolean; sourceDirty?: boolean }> {
  const inspection = await inspectChezmoiPath(requestedPath, options);
  if (inspection.kind === "managed_target") {
    if (!inspection.sourcePath) throw new Error("CHEZMOI_SOURCE_MISSING: Unable to find canonical source for " + requestedPath);
    if (mode === "replace") {
      if (inspection.sourceIsTemplate) throw new Error("CHEZMOI_TEMPLATE_REPLACE_BLOCKED: Use a targeted patch on " + inspection.sourcePath);
      if (inspection.sourceDirty !== false) throw new Error("CHEZMOI_SOURCE_DIRTY: Full replacement could overwrite existing source changes; use a targeted edit on " + inspection.sourcePath);
      if (!expectedSourceHash) throw new Error("CHEZMOI_SOURCE_HASH_REQUIRED: Read the source and provide its SHA-256 expected_hash before full replacement of " + inspection.sourcePath);
    }
    return {
      path: inspection.sourcePath,
      requestedPath: inspection.requestedPath,
      redirected: true,
      sourceIsTemplate: Boolean(inspection.sourceIsTemplate),
      sourceDirty: inspection.sourceDirty,
    };
  }
  assertInspectionWritable(inspection);
  return { path: inspection.canonicalPath, requestedPath: inspection.requestedPath, redirected: false, sourceIsTemplate: false };
}

/** Guard native filesystem mutations. Never runs chezmoi apply or changes the target itself. */
export async function assertChezmoiMutationAllowed(input: string, options: ChezmoiOptions = {}): Promise<void> {
  const inspection = await inspectChezmoiPath(input, options);
  assertInspectionWritable(inspection);
}

function assertInspectionWritable(inspection: ChezmoiInspection): void {
  if (inspection.kind === "managed_target") {
    throw new Error("CHEZMOI_MANAGED_TARGET_BLOCKED: " + inspection.requestedPath +
      " is managed. Edit source " + inspection.sourcePath + " instead; do not apply automatically." +
      (inspection.sourceDirty ? " Source already has uncommitted changes; inspect the diff first." : "") +
      (inspection.sourceIsTemplate ? " This is a template; preserve templating." : ""));
  }
  if (inspection.kind === "generated_target") {
    throw new Error("CHEZMOI_GENERATED_TARGET_BLOCKED: " + inspection.requestedPath + " is generated. " +
      inspection.generatedMarker + ". Use the owning generator.");
  }
  if (inspection.kind === "unavailable") {
    throw new Error("CHEZMOI_LOOKUP_FAILED: " + inspection.explanation + ". No edit was performed.");
  }
}
