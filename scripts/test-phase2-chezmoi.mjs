import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { inspectChezmoiPath, assertChezmoiMutationAllowed, resolveChezmoiEditTarget } from "../dist/lib/chezmoi-guard.js";
import { executeSafeEdit } from "../dist/lib/safe-edit.js";
import { applyMultiFilePatch } from "../dist/lib/patch.js";
import { resetSecurityPolicy, getSecurityPolicy } from "../dist/lib/security-policy.js";

const root = await fs.mkdtemp(path.join(os.tmpdir(), "local-coder-chezmoi-phase2-"));
const src = path.join(root, "source");
const dest = path.join(root, "home");
const live = path.join(dest, ".config", "demo");
const source = path.join(src, "dot_config", "demo");
const previousSource = process.env.LOCAL_CODER_CHEZMOI_SOURCE_DIR;
const previousDest = process.env.LOCAL_CODER_CHEZMOI_DESTINATION_DIR;
let passed = 0;

function check(label) {
  passed += 1;
  console.log("OK  " + label);
}

try {
  await fs.mkdir(live, { recursive: true });
  await fs.mkdir(source, { recursive: true });
  const managed = path.join(live, "managed.conf");
  const sourceManaged = path.join(source, "managed.conf");
  const template = path.join(live, "templated.conf");
  const sourceTemplate = path.join(source, "templated.conf.tmpl");
  const generated = path.join(live, "generated.conf");
  const unmanaged = path.join(live, "local.conf");

  await fs.writeFile(managed, "live managed\n");
  await fs.writeFile(sourceManaged, "original source\nuser-setting=keep\n");
  await fs.writeFile(template, "rendered template\n");
  await fs.writeFile(sourceTemplate, "template content\n{{ .foo }}\n");
  await fs.writeFile(generated, "# Generated by test-runner. Do not edit by hand.\nvalue=1\n");
  await fs.writeFile(unmanaged, "custom local\n");
  const gitInit = spawnSync("git", ["init", "--quiet", src], { encoding: "utf8" });
  assert.equal(gitInit.status, 0, gitInit.stderr);

  process.env.LOCAL_CODER_CHEZMOI_SOURCE_DIR = src;
  process.env.LOCAL_CODER_CHEZMOI_DESTINATION_DIR = dest;
  resetSecurityPolicy("managed");
  process.env.CHECKPOINT_ENABLED = "false";
  process.env.AUDIT_LOG_PATH = path.join(root, "test-audit.log");

  const m = await inspectChezmoiPath(managed);
  assert.equal(m.kind, "managed_target");
  assert.equal(m.sourcePath, sourceManaged);
  assert.equal(m.sourceDirty, true, "Existing uncommitted source must be detected");
  check("managed live path resolves to canonical source and detects uncommitted changes");

  const tpl = await inspectChezmoiPath(template);
  assert.equal(tpl.kind, "managed_target");
  assert.equal(tpl.sourcePath, sourceTemplate);
  assert.equal(tpl.sourceIsTemplate, true);
  check("template target maps to its .tmpl source");

  const gen = await inspectChezmoiPath(generated);
  assert.equal(gen.kind, "generated_target");
  assert.match(gen.generatedMarker, /generated by/i);
  check("generated output with do-not-edit comment detected");

  assert.equal((await inspectChezmoiPath(unmanaged)).kind, "unmanaged");
  check("unmanaged destination distinguished from managed");

  assert.equal((await inspectChezmoiPath(sourceManaged)).kind, "source");
  check("source path recognized and never remapped");

  const alias = path.join(live, "alias.conf");
  await fs.symlink(managed, alias);
  await assert.rejects(assertChezmoiMutationAllowed(alias), /CHEZMOI_MANAGED_TARGET_BLOCKED/);
  check("symlink alias into managed target blocked");

  await assert.rejects(executeSafeEdit({ path: managed, content: "replacement" }), /CHEZMOI_MANAGED_TARGET_BLOCKED/);
  assert.equal(await fs.readFile(managed, "utf8"), "live managed\n");
  check("native safe edit refuses managed live target without modification");

  await assert.rejects(executeSafeEdit({ path: generated, content: "replacement" }), /CHEZMOI_GENERATED_TARGET_BLOCKED/);
  assert.match(await fs.readFile(generated, "utf8"), /value=1/);
  check("native safe edit refuses generated output without modification");

  const normal = await executeSafeEdit({ path: unmanaged, content: "updated custom\n" });
  assert.equal(normal.ok, true);
  assert.equal(await fs.readFile(unmanaged, "utf8"), "updated custom\n");
  check("ordinary unmanaged target edits still work");

  const sourceResult = await executeSafeEdit({ path: sourceManaged, content: "updated source\nuser-setting=keep\n" });
  assert.equal(sourceResult.ok, true);
  assert.equal(await fs.readFile(managed, "utf8"), "live managed\n");
  check("explicit source edit succeeds without automatically applying target");

  const routed = await resolveChezmoiEditTarget(managed, "targeted");
  assert.equal(routed.path, sourceManaged);
  assert.equal(routed.redirected, true);
  check("managed edit automatically resolves to source");

  await assert.rejects(resolveChezmoiEditTarget(template, "replace"), /CHEZMOI_TEMPLATE_REPLACE_BLOCKED/);
  await assert.rejects(resolveChezmoiEditTarget(managed, "replace"), /CHEZMOI_SOURCE_DIRTY|CHEZMOI_SOURCE_HASH_REQUIRED/);
  check("unconditional source replacement and template clobbering blocked");

  const newFile = path.join(live, "should-not-exist.conf");
  const forbiddenPatch = [
    "*** Begin Patch",
    "*** Add File: " + newFile,
    "+new file",
    "*** Delete File: " + managed,
    "*** End Patch",
  ].join("\n");
  await assert.rejects(applyMultiFilePatch(forbiddenPatch, { base_dir: dest }), /CHEZMOI_MANAGED_TARGET_BLOCKED/);
  await assert.rejects(fs.stat(newFile), { code: "ENOENT" });
  check("multi-file delete of managed target rejects before partial writes");

  const updatePatch = [
    "*** Begin Patch",
    "*** Update File: " + managed,
    "@@",
    "-updated source",
    "+updated through source patch",
    "*** End Patch",
  ].join("\n");
  const patchResults = await applyMultiFilePatch(updatePatch, { base_dir: dest });
  assert.equal(patchResults[0].path, sourceManaged);
  assert.equal(await fs.readFile(sourceManaged, "utf8"), "updated through source patch\nuser-setting=keep\n");
  assert.equal(await fs.readFile(managed, "utf8"), "live managed\n");
  check("multi-file update edits canonical source, never live target");

  const handlers = new Map();
  const { registerFilesystemTools } = await import("../dist/tools/filesystem.js");
  registerFilesystemTools({ registerTool: (name, _config, fn) => { handlers.set(name, fn); return {}; } });
  const changed = await handlers.get("edit_file")({
    path: managed, old_text: "updated through source patch", new_text: "targeted edit", replace_all: false, dry_run: false,
  });
  assert.equal(changed.structuredContent.data.path, sourceManaged);
  assert.equal(changed.structuredContent.data.source_redirected, true);
  assert.equal(changed.structuredContent.data.documentation.status, "pending_user_acceptance");
  assert.equal(await fs.readFile(sourceManaged, "utf8"), "targeted edit\nuser-setting=keep\n");
  assert.equal(await fs.readFile(managed, "utf8"), "live managed\n");
  check("MCP edit_file handler automatically redirects to source");

  const tplEdit = await handlers.get("edit_file")({
    path: template, old_text: "template content", new_text: "template retained", replace_all: false, dry_run: false,
  });
  assert.equal(tplEdit.structuredContent.data.path, sourceTemplate);
  assert.equal(await fs.readFile(template, "utf8"), "rendered template\n");
  assert.equal(await fs.readFile(sourceTemplate, "utf8"), "template retained\n{{ .foo }}\n");
  check("MCP template target edit preserves untouched template directives");

  const multiResult = await handlers.get("multi_edit")({
    path: managed, edits: [{old_text:"targeted edit",new_text:"multi edit",replace_all:false}], dry_run:false,
  });
  assert.equal(multiResult.structuredContent.data.path, sourceManaged);
  const regexResult = await handlers.get("replace_regex")({
    path: managed, pattern: "multi edit", replacement:"regex edit", flags:"g", dry_run:false,
  });
  assert.equal(regexResult.structuredContent.data.path, sourceManaged);
  check("MCP multi_edit and replace_regex redirect to managed source");

  const singlePatch = await handlers.get("apply_patch")({
    path: managed, patch:"@@\n-regex edit\n+single patch edit", dry_run:false,
  });
  assert.equal(singlePatch.structuredContent.data.path, sourceManaged);
  assert.equal(await fs.readFile(sourceManaged, "utf8"), "single patch edit\nuser-setting=keep\n");
  assert.equal(await fs.readFile(managed, "utf8"), "live managed\n");
  check("MCP single-file patch routes to canonical source");

  await assert.rejects(handlers.get("write_file")({ path: managed, content: "unsafe full replacement" }), /CHEZMOI_SOURCE_DIRTY|CHEZMOI_SOURCE_HASH_REQUIRED/);
  await assert.rejects(handlers.get("write_file")({ path: template, content: "unsafe template replacement" }), /CHEZMOI_TEMPLATE_REPLACE_BLOCKED/);
  await assert.rejects(handlers.get("edit_file")({ path: generated, old_text: "value=1", new_text: "value=2", dry_run:false }), /CHEZMOI_GENERATED_TARGET_BLOCKED/);
  check("MCP full replacements/templates/generated outputs retain protections");

  const policy = getSecurityPolicy();
  for (const command of ["chezmoi apply", "chezmoi --source /tmp/config apply --dry-run"]) {
    const checkResult = policy.authorizeCommand(command);
    assert.equal(checkResult.operationClass, "high_risk");
    assert.equal(checkResult.allowed, false);
  }
  check("direct chezmoi apply commands require separate authorization");

  const missingCommand = await inspectChezmoiPath(managed, { executable: "/nonexistent/chezmoi" });
  assert.equal(missingCommand.kind, "unavailable");
  await assert.rejects(assertChezmoiMutationAllowed(managed, { executable: "/nonexistent/chezmoi" }), /CHEZMOI_LOOKUP_FAILED/);
  check("lookup failures fail closed instead of overwriting");

} finally {
  if (previousSource === undefined) delete process.env.LOCAL_CODER_CHEZMOI_SOURCE_DIR;
  else process.env.LOCAL_CODER_CHEZMOI_SOURCE_DIR = previousSource;
  if (previousDest === undefined) delete process.env.LOCAL_CODER_CHEZMOI_DESTINATION_DIR;
  else process.env.LOCAL_CODER_CHEZMOI_DESTINATION_DIR = previousDest;
  await fs.rm(root, { recursive: true, force: true });
}

console.log("\nPhase 2: " + passed + " checks passed.");
