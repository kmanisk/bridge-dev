#!/usr/bin/env node
/**
 * Deterministic native tool counts from actual in-memory MCP tools/list discovery.
 * --check <docs-root> fails on missing/stale markers.
 * --write <docs-root> updates only the marker blocks, never any other docs.
 * --json prints the verified tool manifest.
 */
import fs from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { createMcpServer } from "../dist/server-factory.js";
import { classifyTool, NATIVE_TOOL_CLASSES, EXPECTED_NATIVE_REGISTRATION_COUNT } from "../dist/lib/tool-classification.js";

const profiles = ["slim","full"];
const counts={};
const names={};
const fakeUpstream={registerMcpServer() {},listStatuses:async()=>[],getServerConfig:()=>undefined};
for(const profile of profiles){
  process.env.CHATGPT_TOOL_PROFILE=profile;
  const server=createMcpServer(process.cwd(),10,[process.cwd()],false,fakeUpstream);
  const client=new Client({name:"policygate-tool-counts",version:"1"},{capabilities:{}});
  const [a,b]=InMemoryTransport.createLinkedPair();
  try{
    await server.connect(a);await client.connect(b);
    const results=await client.listTools();
    names[profile]=(results.tools??[]).map(x=>x.name).sort();
    counts[profile]=names[profile].length;
  }finally{await client.close();await server.close();}
}
if(Object.keys(NATIVE_TOOL_CLASSES).length!==EXPECTED_NATIVE_REGISTRATION_COUNT ||
  counts.full!==EXPECTED_NATIVE_REGISTRATION_COUNT ||
  names.full.some(name=>!(name in NATIVE_TOOL_CLASSES)))
  throw new Error("POLICYGATE_TOOL_MANIFEST_DRIFT: discovered registrations and classifications do not match");
const fingerprint=createHash("sha256").update(JSON.stringify(
  names.full.map(name=>[name,classifyTool(name,{}).kind])
)).digest("hex");
const data={slim:counts.slim,full:counts.full,native_registrations:counts.full,fingerprint,tools:names};
const begin="<!-- LOCAL-CODER-TOOL-COUNT:BEGIN -->",end="<!-- LOCAL-CODER-TOOL-COUNT:END -->";
const block=[begin,
  "BridgeDev gateway tool discovery (isolated in-memory `tools/list`, not a live deployment check): **"+
  counts.slim+" slim / "+counts.full+" full**; "+counts.full+" classified native registrations.",
  "Tool-registration SHA-256: `"+fingerprint+"`. Generated by BridgeDev `scripts/sync-tool-counts.mjs`.",
  end].join("\n");
const args=process.argv.slice(2),mode=args[0],root=args[1];
if(mode==="--json"){console.log(JSON.stringify(data,null,2));process.exit(0);}
if((mode==="--check-manifest" || mode==="--write-manifest") && root){
  const filename=path.resolve(root);
  const expected=JSON.stringify(data,null,2)+"\n";
  if(mode==="--check-manifest"){
    const saved=await fs.readFile(filename,"utf8");
    if(saved!==expected)throw Error("STALE_TOOL_MANIFEST: registry changed; regenerate and review "+filename);
    console.log("OK verified native tool-count manifest: "+filename);
  }else{
    await fs.writeFile(filename,expected);
    console.log("WROTE native tool-count manifest: "+filename);
  }
  process.exit(0);
}
if(!["--check","--write"].includes(mode)||!root)throw Error("Usage: node scripts/sync-tool-counts.mjs --check|--write <docs-root> | --json");
for(const rel of ["AGENTS.md","docs/system/SYSTEM_CONTEXT.md"]){
  const filename=path.resolve(root,rel);
  const original=await fs.readFile(filename,"utf8");
  const start=original.indexOf(begin),stop=original.indexOf(end);
  let next;
  if(start<0 && stop<0){
    const lineEnd=original.indexOf("\n");
    next=original.slice(0,lineEnd+1)+"\n"+block+"\n"+original.slice(lineEnd+1);
  }else if(start>=0 && stop>start){
    next=original.slice(0,start)+block+original.slice(stop+end.length);
  }else throw new Error("Malformed LOCAL-CODER-TOOL-COUNT marker in "+filename);
  if(mode==="--check" && next!==original)throw Error("STALE_TOOL_COUNTS: "+filename+" — regenerate and review before merging");
  if(mode==="--write" && next!==original)await fs.writeFile(filename,next);
  console.log((next===original?"OK ":"UPDATED ")+filename);
}
console.log("Registered tools: slim="+counts.slim+", full="+counts.full+", sha256="+fingerprint);
