import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {PolicyGate,newPolicySession} from '../dist/lib/policy-gateway.js';
import {requestIdentity} from '../dist/lib/request-identity.js';
if(!process.env.BRIDGEDEV_TEST_ROOT)throw Error('Use isolated-tests.mjs');
const config=JSON.parse(await fs.readFile(process.env.POLICYGATE_POLICY_FILE,'utf8'));
config.audit_log=path.join(process.env.BRIDGEDEV_TEST_ROOT,'capability-audit.jsonl');
const filename=path.join(process.env.BRIDGEDEV_TEST_ROOT,'capability-policy.json');await fs.writeFile(filename,JSON.stringify(config));
const gate=new PolicyGate(filename),origin=newPolicySession();
const documents=await Promise.all(config.context_files.map(async(p,i)=>({kind:i?'current_state':'agents',path:p,sha256:createHash('sha256').update(await fs.readFile(p)).digest('hex')})));
const identity=(subject,fn)=>requestIdentity.run({subject},fn);
await identity('fixture-subject',()=>gate.contextLoaded(origin,{docs:['agents','current_state']},{documents}));
let proof=identity('fixture-subject',()=>gate.issueContextToken(origin));assert.ok(proof);
assert.equal(await identity('different-subject',()=>gate.acceptContextToken(newPolicySession(),proof.context_token)),false);
assert.equal(await identity('fixture-subject',()=>gate.acceptContextToken(newPolicySession(),proof.context_token)),true);
await gate.invalidateContext(origin,'fixture_operator_revoke',true);
assert.equal(await identity('fixture-subject',()=>gate.acceptContextToken(newPolicySession(),proof.context_token)),false);
const expiring=newPolicySession();expiring.expiresAt=Date.now()+40;
await identity('fixture-subject',()=>gate.contextLoaded(expiring,{docs:['agents','current_state']},{documents}));
proof=identity('fixture-subject',()=>gate.issueContextToken(expiring));await new Promise(r=>setTimeout(r,60));
assert.equal(await identity('fixture-subject',()=>gate.acceptContextToken(newPolicySession(),proof.context_token)),false);
const restored=new PolicyGate(filename);
assert.equal(await identity('fixture-subject',()=>restored.acceptContextToken(newPolicySession(),proof.context_token)),false);
console.log('Context capability subject isolation, explicit proof, revocation, expiry and restart invalidation PASS');
